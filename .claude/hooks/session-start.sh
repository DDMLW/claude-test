#!/bin/bash
# SessionStart hook for Claude Code cloud sessions.
#
# Prepares the literature-search skills vendored in .claude/skills:
#   - paper-search-pro: installs its Python dependencies and rebuilds
#     ~/.paper-search-pro/config.yaml, the only place it reads credentials from
#     (the home directory does not survive between cloud sessions).
#   - research-lit (ARIS): its helpers in .aris/tools read OPENALEX_API_KEY and
#     SEMANTIC_SCHOLAR_API_KEY directly; the contact email is exported below.
#
# Credentials come from environment variables set in the cloud environment's
# settings: OPENALEX_API_KEY, SEMANTIC_SCHOLAR_API_KEY, RESEARCH_EMAIL
# (NCBI_API_KEY is optional). Values are never printed.
set -euo pipefail

if [ "${CLAUDE_CODE_REMOTE:-}" != "true" ]; then
  exit 0
fi

PSP_HOME="$CLAUDE_PROJECT_DIR/.claude/skills/paper-search-pro"

# 1. Python dependencies. pip skips anything already installed, so reruns are cheap.
pip_install() {
  python3 -m pip install --quiet --disable-pip-version-check --root-user-action=ignore "$@" \
    -r "$PSP_HOME/scripts/requirements.txt" >&2
}
pip_install || pip_install --break-system-packages

# 2. paper-search-pro config, written only when at least one credential is set.
if [ -n "${OPENALEX_API_KEY:-}${SEMANTIC_SCHOLAR_API_KEY:-}${RESEARCH_EMAIL:-}${NCBI_API_KEY:-}" ]; then
  python3 - <<'PY'
import json
import os
import pathlib

email = os.environ.get("RESEARCH_EMAIL", "")
fields = {
    "openalex_api_key": os.environ.get("OPENALEX_API_KEY", ""),
    "openalex_email": os.environ.get("OPENALEX_EMAIL", email),
    "semantic_scholar_api_key": os.environ.get("SEMANTIC_SCHOLAR_API_KEY", ""),
    "ncbi_email": email,
    "ncbi_api_key": os.environ.get("NCBI_API_KEY", ""),
    "crossref_email": email,
}
path = pathlib.Path.home() / ".paper-search-pro" / "config.yaml"
path.parent.mkdir(parents=True, exist_ok=True)
# JSON strings are valid YAML double-quoted scalars, so this quotes safely.
lines = [f"{key}: {json.dumps(value)}" for key, value in fields.items() if value]
fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w", encoding="utf-8") as f:
    f.write("# Generated by .claude/hooks/session-start.sh from environment variables.\n")
    f.write("\n".join(lines) + "\n")
os.chmod(path, 0o600)
PY
fi

# 3. Session environment for the skills.
if [ -n "${CLAUDE_ENV_FILE:-}" ]; then
  printf 'export PSP_HOME=%q\n' "$PSP_HOME" >> "$CLAUDE_ENV_FILE"
  if [ -n "${RESEARCH_EMAIL:-}" ] && [ -z "${ARIS_VERIFY_EMAIL:-}" ]; then
    printf 'export ARIS_VERIFY_EMAIL=%q\n' "$RESEARCH_EMAIL" >> "$CLAUDE_ENV_FILE"
  fi
  if [ -n "${RESEARCH_EMAIL:-}" ] && [ -z "${OPENALEX_EMAIL:-}" ]; then
    printf 'export OPENALEX_EMAIL=%q\n' "$RESEARCH_EMAIL" >> "$CLAUDE_ENV_FILE"
  fi
fi

# 4. One status line for Claude's context: which credentials are set, and
#    whether the environment's network policy lets the scholarly APIs through.
state() {
  if [ -n "${!1:-}" ]; then echo "set"; else echo "missing"; fi
}
blocked=""
for host in api.openalex.org export.arxiv.org api.semanticscholar.org; do
  code=$(curl -s -o /dev/null -m 5 -w '%{http_code}' "https://$host/" || true)
  if [ "$code" = "000" ]; then
    blocked="$blocked $host"
  fi
done
echo "[literature skills] Python deps ready. OPENALEX_API_KEY=$(state OPENALEX_API_KEY), SEMANTIC_SCHOLAR_API_KEY=$(state SEMANTIC_SCHOLAR_API_KEY), RESEARCH_EMAIL=$(state RESEARCH_EMAIL)."
if [ -n "$blocked" ]; then
  echo "[literature skills] Unreachable from this environment (network policy?):$blocked. See README.md for the domains to allow."
fi
